"""Training loop. Produces artifacts; computes NO headline metrics (V1 rule:
every headline number is derived by analyze.py from saved artifacts alone, so
a training-loop bug cannot silently produce favourable metrics, and metrics
added later apply retroactively without retraining).

Free-arm loss is task cross-entropy + lambda_use * rent, full stop. The rent
is L1 on the SOFT atom-selection mass per micro-step (the same soft
distribution the straight-through sample uses), pass exempt, charged per
APPLICATION. Oracle terms exist only behind cfg.forced_routing (E0 arm
'A0-oracle'), and the oracle module is imported only on that path.

Per-run outputs (everything needed to reproduce results without retraining):
  config.json, env.json, split_ref.json, data_manifest.json,
  init_calibration.json, param_counts.json, train_log.jsonl,
  evals/step{N}.json every eval_every steps,
  traces/step{N}.npz at checkpoint cadence,
  checkpoints/step{N}.pt every ckpt_every steps, every registered panel step,
  and final.pt,
  SHA256SUMS (regenerated by the driver after panel + analyze).
"""
from __future__ import annotations

import time
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F

from . import data as data_mod
from . import registered as R
from . import split as split_mod
from .config import Config, run_dir_for
from .evaluate import run_eval
from .model import AtomModel, param_counts
from .utils import (JsonlLogger, check_rss, env_info, require_clean_tree,
                    seed_everything, set_threads, stream_rng, stream_seed,
                    write_json)


def _tau_at(cfg: Config, step: int) -> float:
    frac = min(step / max(cfg.tau_anneal_steps, 1), 1.0)
    return cfg.tau_start + (cfg.tau_end - cfg.tau_start) * frac


def _lr_at(cfg: Config, step: int) -> float:
    if step < cfg.warmup_steps:
        return cfg.lr * (step + 1) / cfg.warmup_steps
    return cfg.lr


def train_run(cfg: Config, out: str | None = None, allow_dirty: bool = False) -> Path:
    git = require_clean_tree(allow_dirty)
    set_threads()
    seed_everything(cfg.seed)

    run_dir = run_dir_for(cfg, out)
    if (run_dir / "checkpoints" / "final.pt").exists():
        raise SystemExit(f"{run_dir} already has a final checkpoint; refusing "
                         "to overwrite a completed run.")
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "checkpoints").mkdir(exist_ok=True)
    (run_dir / "evals").mkdir(exist_ok=True)
    (run_dir / "traces").mkdir(exist_ok=True)

    bundle = data_mod.build_bundle(cfg)
    arrays = data_mod.build_epoch_arrays(bundle, cfg,
                                         include_partials=cfg.forced_routing)
    n_examples = len(arrays["x"])
    steps_per_epoch = n_examples // cfg.batch_size

    model = AtomModel(cfg)
    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg.lr,
                                  betas=cfg.betas, weight_decay=cfg.weight_decay)
    gumbel_gen = torch.Generator().manual_seed(
        int(stream_seed(cfg.seed, "gumbel").generate_state(1)[0]))

    if cfg.forced_routing:
        from . import oracle  # QUARANTINE: imported only on the A0-oracle path

    write_json(run_dir / "config.json", cfg.to_dict())
    write_json(run_dir / "split_ref.json", split_mod.split_ref())
    write_json(run_dir / "data_manifest.json", data_mod.data_manifest(bundle))
    write_json(run_dir / "param_counts.json", param_counts(model))
    log = JsonlLogger(run_dir / "train_log.jsonl")
    log.log(event="start", run_dir=str(run_dir), arm=cfg.arm, seed=cfg.seed,
            n_train_presentations_per_epoch=n_examples,
            steps_per_epoch=steps_per_epoch, **git)

    # ------------------------------------------------------------------
    # Registered init calibration: raw rent magnitude vs task loss BEFORE
    # any update, so the lambda grid's scale is on record per run.
    # ------------------------------------------------------------------
    model.eval()
    with torch.no_grad():
        xb = torch.from_numpy(arrays["x"][: cfg.batch_size])
        yb = torch.from_numpy(arrays["y"][: cfg.batch_size])
        tb = torch.from_numpy(arrays["tokens"][: cfg.batch_size])
        nb = torch.from_numpy(arrays["n_tokens"][: cfg.batch_size])
        out0 = model(xb, tb, nb, mode="gumbel", tau=_tau_at(cfg, 0),
                     generator=gumbel_gen)
        task0 = F.cross_entropy(out0["logits"].reshape(-1, cfg.vocab),
                                yb.reshape(-1)).item()
        rent0 = out0["soft_atom_mass"].sum(dim=1).mean().item()
    init_cal = {"loss_task_init": task0, "rent_raw_init": rent0,
                "lambda_use": cfg.lambda_use,
                "rent_weighted_init": cfg.lambda_use * rent0,
                "rent_over_task_init": (cfg.lambda_use * rent0 / task0
                                        if task0 > 0 else None)}
    write_json(run_dir / "init_calibration.json", init_cal)
    log.log(event="init_calibration", **init_cal)

    # ------------------------------------------------------------------
    # The loop: fixed budget, no early stopping, final checkpoint = result.
    # ------------------------------------------------------------------
    t0 = time.time()
    peak_rss = 0.0
    step = 0
    epoch = 0
    while step < cfg.total_steps:
        order = stream_rng(cfg.seed, "shuffle", epoch).permutation(n_examples)
        for b in range(steps_per_epoch):
            if step >= cfg.total_steps:
                break
            idx = order[b * cfg.batch_size:(b + 1) * cfg.batch_size]
            xb = torch.from_numpy(arrays["x"][idx])
            yb = torch.from_numpy(arrays["y"][idx])
            tb = torch.from_numpy(arrays["tokens"][idx])
            nb = torch.from_numpy(arrays["n_tokens"][idx])
            tau = _tau_at(cfg, step)
            lr = _lr_at(cfg, step)
            for g in optimizer.param_groups:
                g["lr"] = lr

            model.train()
            if cfg.forced_routing:
                sched = torch.from_numpy(oracle.forced_schedule(
                    arrays["tokens"][idx], arrays["n_tokens"][idx]))
                out = model(xb, tb, nb, mode="forced", forced=sched, tau=tau)
            else:
                out = model(xb, tb, nb, mode="gumbel", tau=tau,
                            generator=gumbel_gen)

            loss_task = F.cross_entropy(out["logits"].reshape(-1, cfg.vocab),
                                        yb.reshape(-1))
            rent_raw = out["soft_atom_mass"].sum(dim=1).mean()
            loss = loss_task + cfg.lambda_use * rent_raw
            record = {"loss_task": loss_task.item(),
                      "loss_rent_raw": rent_raw.item(),
                      "loss_rent_weighted": cfg.lambda_use * rent_raw.item()}
            if cfg.forced_routing:
                oracle_terms = oracle.oracle_losses(
                    model, out, xb, tb, nb,
                    torch.from_numpy(arrays["y_partial"][idx]), cfg)
                loss = loss + oracle_terms.pop("oracle_total")
                record.update({k: v.item() for k, v in oracle_terms.items()})

            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            grad_norm = torch.nn.utils.clip_grad_norm_(
                model.parameters(), cfg.grad_clip)
            optimizer.step()
            step += 1
            save_checkpoint = (step % cfg.ckpt_every == 0
                               or step in cfg.panel_steps
                               or step == cfg.total_steps)

            if step % cfg.log_every == 0 or step == 1:
                with torch.no_grad():
                    batch_acc = (out["logits"].argmax(-1) == yb).all(-1
                                 ).float().mean().item()
                log.log(event="step", step=step, epoch=epoch, lr=lr, tau=tau,
                        loss=loss.item(), grad_norm=float(grad_norm),
                        batch_acc=batch_acc, **record)

            if step % cfg.eval_every == 0 or step == cfg.total_steps:
                summary, traces = run_eval(model, bundle, cfg, step)
                write_json(run_dir / "evals" / f"step{step:06d}.json", summary)
                if save_checkpoint:
                    np.savez_compressed(
                        run_dir / "traces" / f"step{step:06d}.npz", **traces)
                s = summary["sets"]
                log.log(event="eval", step=step,
                        seen_hard=s["seen_heldout"]["mean_acc_hard"],
                        L1_hard=s["unseen_L1"]["mean_acc_hard"],
                        L2_hard=s["unseen_L2"]["mean_acc_hard"],
                        L3_hard=s["unseen_L3"]["mean_acc_hard"],
                        closed_map_seen=s["seen_heldout"]["mean_closed_map_error"],
                        atoms_in_use=summary["routing"]["atoms_in_use"],
                        pass_rate=summary["routing"]["pass_rate"],
                        steps_per_token=summary["routing"]["steps_per_token"])
                peak_rss = max(peak_rss, check_rss())

            if save_checkpoint:
                torch.save({"model": model.state_dict(),
                            "config": cfg.to_dict(), "step": step},
                           run_dir / "checkpoints" / f"step{step:06d}.pt")
        epoch += 1

    torch.save({"model": model.state_dict(), "config": cfg.to_dict(),
                "step": step}, run_dir / "checkpoints" / "final.pt")
    write_json(run_dir / "env.json", {
        **env_info(), **git, "train_seconds": time.time() - t0,
        "peak_rss_gb": peak_rss})
    log.log(event="done", step=step, train_seconds=time.time() - t0,
            peak_rss_gb=peak_rss)
    log.close()
    return run_dir


if __name__ == "__main__":
    import argparse
    from .config import config_for_arm
    ap = argparse.ArgumentParser(description="Train one V2 run")
    ap.add_argument("--arm", required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--out", default=None)
    ap.add_argument("--allow-dirty", action="store_true")
    a = ap.parse_args()
    cfg = config_for_arm(a.arm, a.seed, smoke=a.smoke)
    print(train_run(cfg, out=a.out, allow_dirty=a.allow_dirty))
